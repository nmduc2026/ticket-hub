package com.ndz.shared.exception;

import org.springframework.http.HttpStatus;

/**
 * Mã lỗi nghiệp vụ ổn định cho frontend (trường {@code code} của Problem Details) cùng trạng thái HTTP mặc định.
 * Thêm mã mới ở đây; tên hằng số chính là giá trị {@code code} trả ra.
 */
public enum ErrorCode {

	// Chung
	UNAUTHENTICATED(HttpStatus.UNAUTHORIZED),
	FORBIDDEN(HttpStatus.FORBIDDEN),
	VALIDATION_FAILED(HttpStatus.BAD_REQUEST),
	INTERNAL_ERROR(HttpStatus.INTERNAL_SERVER_ERROR),

	// Idempotency-Key
	IDEMPOTENCY_KEY_REQUIRED(HttpStatus.BAD_REQUEST),
	IDEMPOTENCY_KEY_INVALID(HttpStatus.BAD_REQUEST),
	IDEMPOTENCY_KEY_REUSED(HttpStatus.UNPROCESSABLE_CONTENT),
	REQUEST_IN_PROGRESS(HttpStatus.CONFLICT),
	PAYLOAD_TOO_LARGE(HttpStatus.CONTENT_TOO_LARGE),

	// Account
	PROFILE_NOT_FOUND(HttpStatus.NOT_FOUND),
	EMAIL_REQUIRED(HttpStatus.UNPROCESSABLE_CONTENT),
	PHONE_INVALID(HttpStatus.UNPROCESSABLE_CONTENT),
	USER_NOT_FOUND(HttpStatus.NOT_FOUND),
	CANNOT_LOCK_SELF(HttpStatus.UNPROCESSABLE_CONTENT),
	IDENTITY_PROVIDER_UNAVAILABLE(HttpStatus.SERVICE_UNAVAILABLE),

	// Organizer (Catalog)
	APPLICATION_ALREADY_PENDING(HttpStatus.CONFLICT),
	ALREADY_ORGANIZER(HttpStatus.CONFLICT),
	APPLICATION_NOT_FOUND(HttpStatus.NOT_FOUND),
	ORGANIZER_NOT_FOUND(HttpStatus.NOT_FOUND),
	ORGANIZER_NOT_PENDING(HttpStatus.CONFLICT),
	LEGAL_ID_INVALID(HttpStatus.UNPROCESSABLE_CONTENT),
	WEBSITE_INVALID(HttpStatus.UNPROCESSABLE_CONTENT),

	// Catalog
	EVENT_NOT_FOUND(HttpStatus.NOT_FOUND),
	EVENT_LOCKED(HttpStatus.CONFLICT),
	INVALID_EVENT_TIMES(HttpStatus.UNPROCESSABLE_CONTENT),
	DOORS_OPEN_AFTER_START(HttpStatus.UNPROCESSABLE_CONTENT),
	INVALID_EVENT_TRANSITION(HttpStatus.CONFLICT),
	ORGANIZER_NOT_REGISTERED(HttpStatus.FORBIDDEN),
	PUBLISH_NOT_ALLOWED(HttpStatus.CONFLICT),
	PUBLISH_INCOMPLETE(HttpStatus.UNPROCESSABLE_CONTENT),
	VENUE_NOT_FOUND(HttpStatus.NOT_FOUND),
	VENUE_REQUIRED(HttpStatus.UNPROCESSABLE_CONTENT),
	SEAT_MAP_REQUIRED(HttpStatus.UNPROCESSABLE_CONTENT),
	SEAT_MAP_NOT_IN_VENUE(HttpStatus.UNPROCESSABLE_CONTENT),
	SECTION_NOT_IN_SEAT_MAP(HttpStatus.UNPROCESSABLE_CONTENT),
	DUPLICATE_SECTION(HttpStatus.UNPROCESSABLE_CONTENT),
	TIER_NOT_FOUND(HttpStatus.NOT_FOUND),
	EMPTY_FILE(HttpStatus.UNPROCESSABLE_CONTENT),
	IMAGE_TOO_LARGE(HttpStatus.UNPROCESSABLE_CONTENT),
	UNSUPPORTED_IMAGE_TYPE(HttpStatus.UNPROCESSABLE_CONTENT),

	// Booking
	SEAT_HOLD_UNAVAILABLE(HttpStatus.SERVICE_UNAVAILABLE),
	BOOKING_NOT_FOUND(HttpStatus.NOT_FOUND),
	BOOKING_NOT_CANCELLABLE(HttpStatus.CONFLICT),
	INVALID_BOOKING_TRANSITION(HttpStatus.CONFLICT),
	EVENT_NOT_ON_SALE(HttpStatus.CONFLICT),
	SEAT_UNAVAILABLE(HttpStatus.CONFLICT),
	PENDING_BOOKING_EXISTS(HttpStatus.CONFLICT),
	MAX_SEATS_EXCEEDED(HttpStatus.UNPROCESSABLE_CONTENT),
	TICKET_LIMIT_EXCEEDED(HttpStatus.UNPROCESSABLE_CONTENT),
	DUPLICATE_SEATS(HttpStatus.UNPROCESSABLE_CONTENT),
	HOLD_EXPIRING(HttpStatus.CONFLICT),
	BOOKING_NOT_PAYABLE(HttpStatus.CONFLICT),
	BOOKING_NOT_REFUNDABLE(HttpStatus.CONFLICT),
	REFUND_WINDOW_CLOSED(HttpStatus.UNPROCESSABLE_CONTENT),

	// Ticket
	TICKET_NOT_FOUND(HttpStatus.NOT_FOUND),
	TICKET_ALREADY_USED(HttpStatus.CONFLICT),
	TICKET_REVOKED(HttpStatus.CONFLICT),
	NOT_EVENT_OWNER(HttpStatus.FORBIDDEN),
	CHECKIN_NOT_OPEN(HttpStatus.UNPROCESSABLE_CONTENT),
	EVENT_ENDED(HttpStatus.UNPROCESSABLE_CONTENT),

	// Notification
	NOTIFICATION_NOT_FOUND(HttpStatus.NOT_FOUND),
	NOTIFICATION_MANDATORY(HttpStatus.UNPROCESSABLE_CONTENT),
	UNKNOWN_NOTIFICATION_TYPE(HttpStatus.UNPROCESSABLE_CONTENT),

	// Payment
	PAYMENT_PROVIDER_UNAVAILABLE(HttpStatus.SERVICE_UNAVAILABLE),
	WEBHOOK_SIGNATURE_INVALID(HttpStatus.BAD_REQUEST);

	private final HttpStatus status;

	ErrorCode(HttpStatus status) {
		this.status = status;
	}

	public HttpStatus status() {
		return status;
	}

}
